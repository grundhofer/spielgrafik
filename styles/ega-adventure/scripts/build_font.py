def main():
    chars = list(G.keys())
    cols = 16
    rows = (len(chars) + cols - 1) // cols
    img = np.zeros((rows * 8, cols * 8, 4), np.uint8)
    for i, ch in enumerate(chars):
        cy, cx = (i // cols) * 8, (i % cols) * 8
        for y, r in enumerate(G[ch]):
            for x, c in enumerate(r):
                if c == "#":
                    img[cy + y, cx + x] = (255, 255, 255, 255)
    ART.mkdir(parents=True, exist_ok=True)
    Image.fromarray(img, "RGBA").save(ART / "font8.png")
    (ART.parents[1] / "assets").mkdir(exist_ok=True)
    Image.fromarray(img, "RGBA").save(ART.parents[1] / "assets" / "font8.png")   # Kopie als Asset
    (ART / "font8.json").write_text(json.dumps({"cell": 8, "columns": cols, "chars": "".join(chars)},
                                               ensure_ascii=False, indent=1))
    print(f"{len(chars)} Zeichen -> {ART / 'font8.png'}")


if __name__ == "__main__":
    main()
