#!/usr/bin/env python3
"""Eigene 8×8-Systemschrift für den Textbereich (40 Spalten), Fassung 2, CC0.

Fassung 1 war im Bau der PC-Textmodus-Schriften gezeichnet (6 px breit, 2 px Innenraum, Versalien 7 Zeilen) und
lag damit zu nah an bestehenden Schriften: Ein Abgleich gegen die 8×8-Bitmapschriften des „Ultimate Oldschool PC
Font Pack“ (int10h.org, CC BY-SA 4.0) ergab 35 von 88 Zeichen pixelgleich mit der IBM-EGA/CGA-Schrift und 58 mit
einer weiteren Schrift des Pakets. Sie ist verworfen; diese Fassung ist neu gezeichnet und nach eigenen Regeln
gebaut, die bewusst von diesen Schriften abweichen:

  * Breite 7 px (Spalten 0–6), 1 px Abstand (Spalte 7); senkrechte Striche 2 px, waagerechte 1 px, Innenräume
    3 px. Die IBM-Schrift ist 6 px breit mit 2 px Innenraum und 2 px Abstand.
  * Versalien und Ziffern nur 6 Zeilen hoch (Zeilen 1–6), Zeile 0 und 7 bleiben frei; Kleinbuchstaben mit
    x-Höhe 4 Zeilen (Zeilen 3–6), Oberlängen ab Zeile 1, Unterlängen in Zeile 7. Die PC-Schriften haben
    Versalien mit 7 Zeilen und eine x-Höhe von 5 Zeilen.
  * Eigene Formen, wo auch die 6-Zeilen-Höhe noch mit einzelnen Schriften zusammenfiel: A mit runder Kappe und
    tiefem Querbalken (Zeile 4, ebenso H), C und G mit geraden Enden, D eckig, K ohne Eckpunkte, M mit breiten
    Schultern, N mit dünner Diagonale, U, Ü, a, u mit Kerbe unten rechts, Z mit 3 px breiter Schräge, s als
    Zickzack aus zwei 4-px-Balken, v und y spitz, p mit Schulter wie r, 6 mit Bauch unten, 8 mit kleinerem
    oberen Bogen.
  * Umlaute mit zwei 1-px-Punkten in der Mitte (Zeile 0 bei Versalien über einem 5 Zeilen hohen Körper,
    Zeile 1 bei Kleinbuchstaben).

Prüfung (nur lokal, die Vergleichsschriften sind nicht Teil des Eintrags): scripts/font_compare.py zählt je Zeichen
die abweichenden Pixel, kleinster Wert über Verschiebungen um ±1 Zeile/Spalte, gegen alle 60 8×8-Schriften des
Pakets. Ergebnis Fassung 2: von 69 Buchstaben und Ziffern ist nur L mit einer Schrift pixelgleich (ohne
Spielraum); gegen IBM EGA 8x8 keiner (kleinster Abstand 6, Median 12).

Erzeugt
  demo/fonts/font8.png   Atlas 16 Spalten × n Zeilen, je Zeichen 8×8, weiß auf transparent (Kopie assets/font8.png)
  demo/fonts/font8.json  Zeichenfolge des Atlas (Zeichen -> Index)

    .venv/bin/python styles/ega-adventure/scripts/build_font.py
"""
