ARROWS = {
    "▼": """
........
.######.
..####..
...##...
........
........
........
........""",
    "▶": """
.#......
.##.....
.###....
.####...
.###....
.##.....
.#......
........""",
}


def glyphs():
    out = {}
    for ch, rows in G.items():
        t = np.zeros((8, 8), np.int8)
        for y, r in enumerate(rows):
            assert len(r) == 5, (ch, r)
            for x, p in enumerate(r):
                if p == "#":
                    t[y, 1 + x] = 3
        out[ch] = t
    for ch, s in ARROWS.items():
        rows = s.strip("\n").split("\n")
        t = np.zeros((8, 8), np.int8)
        for y, r in enumerate(rows):
            for x, p in enumerate(r):
                if p == "#":
                    t[y, x] = 3
        out[ch] = t
    return out
